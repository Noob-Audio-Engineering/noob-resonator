#!/usr/bin/env node
/**
 * Regenerate `src/previews.js`: the characteristic partial ratios the browse
 * view draws in each object's row.
 *
 * The panel renders and does not compute, so those rows cannot solve a beam
 * equation to draw a thumbnail. They read a table instead — and this writes
 * it, from the design-mode physics, so the table has a stated provenance and
 * a way to be rebuilt rather than being a wall of numbers somebody typed.
 *
 * **The engine is the authority.** When its ratios move, rerun this; better
 * still, replace this script with one that reads them off a running engine.
 *
 *   node tools/gen-previews.mjs
 */
import { writeFileSync } from 'node:fs';
import { OBJECTS } from '../src/objects.js';
import { ratiosOf } from '../src/dev/physics/resonators.js';

/** Enough partials to show the shape of a series at forty-six pixels tall. */
const N = 40;
const opts = { ratio: 1, opening: 0, barSecond: 4, barThird: 9.2 };

const rows = OBJECTS.map((o) => {
  const o2 = { ...opts, opening: o.id === 'tube' ? 1 : 0 };
  const r = ratiosOf(o.id, N, o2).map((v) => Number(v.toPrecision(6)));
  return `  ${o.id}: [${r.join(', ')}],`;
}).join('\n');

const out = `/**
 * Characteristic partial ratios, one row per object, for the browse view's
 * previews — **a generated table, not a computation.**
 *
 * The panel renders and does not compute: every partial it draws for the
 * loaded object arrives on the \`modes\` stream. A browser showing eight
 * objects at once cannot do that, because only one of them is loaded, and
 * solving eight beam equations in the front end to draw eight thumbnails is
 * exactly what this architecture forbids. So the rows read a table.
 *
 * **These are the shape of each series, not your settings.** They are taken
 * at reference settings, so a row shows what an object *is* rather than what
 * it would sound like at your current damping — which is the comparison the
 * browser exists to make anyway.
 *
 * Generated by \`tools/gen-previews.mjs\` from the design-mode physics. The
 * engine is the authority: when its ratios move, regenerate this.
 *
 * @type {Record<string, number[]>}
 */
export const PREVIEW_RATIOS = {
${rows}
};
`;
writeFileSync(new URL('../src/previews.js', import.meta.url), out);
console.log('wrote src/previews.js');
