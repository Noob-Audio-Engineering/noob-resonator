/**
 * Each object's partial series and mode shapes — **development only, and never
 * the source of anything the panel shows when a plug-in is connected.**
 *
 * This whole directory is a quarantine. All of the mathematics in this plug-in
 * belongs to the Rust engine: it computes the partials, the levels and the
 * ring times, and publishes them on the `modes`, `response` and `info`
 * streams. The panel draws what arrives and derives none of it.
 *
 * What this file is for is the hour before that engine exists, and the hour
 * after somebody clones the repository and wants to look at the page. The
 * design manifest in `../manifest.js` uses it to generate the same four
 * streams the engine will, so the panel has something to render — and the
 * panel cannot tell the difference, because it only ever sees a stream.
 *
 * **Nothing outside `src/dev/` may import this**, and nothing does. It is
 * loaded from a dynamic import behind `import.meta.env.DEV`, so a production
 * build does not contain a byte of it.
 *
 * ## The series are the engine's now, and this file no longer solves for them
 *
 * Every ratio here comes from `series-table.js`, which is generated by
 * `tools/gen-previews.mjs` out of `benchmark --dump series`. There used to be
 * a Newton solver for the beam's eigenvalues and a Bessel solver for the round
 * head's, and they were careful and tested and *still the wrong thing to
 * have*: two implementations of every eigenvalue problem in the product, with
 * nothing checking that they agreed. They had already drifted, silently, when
 * the engine appended two objects this page had never heard of.
 *
 * So the line is drawn at **root-finding and special functions, which are the
 * engine's**, against **closed-form algebra over a live control, which stays
 * here** — because a control that does nothing in design mode teaches the
 * wrong thing about the product. What remains is the rectangle's eigenvalues
 * (four lines, and `test/` checks them against the engine's own table), the
 * air column's phase, the stiff-string stretch, and the mode shapes.
 *
 * **One object's shape is not modelled**: the clamped disc's needs a modified
 * Bessel function, which is exactly the kind of machinery that just left. Its
 * contact controls do nothing in design mode and [`SHAPELESS`] says so, so the
 * panel can print it rather than let a dead knob look like a working one.
 *
 * **Two results are worth keeping even so**, both of which came out of writing
 * the tests: the beam ratio everyone quotes, 2.756, is a truncation of 2.75654
 * and not a rounding of it — the correctly rounded figure is 2.757 — and an
 * undercut bar has no closed form at all, so its ratios are a maker's target
 * rather than a solution.
 */
import { SERIES_TABLE, TABLE_LIMIT } from '../series-table.js';

/** Speed of sound in air at 20 °C, m/s. Only the air columns use it, and the panel prints it beside every length it derives. */
export const C_AIR = 343;

export { TABLE_LIMIT };

/**
 * The bare series of an object, `[i, j, ratio]` sorted by frequency, straight
 * off the engine.
 *
 * Bare means at default aspect with no inharmonicity: the controls that move a
 * series are applied on top of this, not baked into it.
 */
export const tableOf = (id) => SERIES_TABLE[id] || SERIES_TABLE.string;

/**
 * The objects whose mode shape this file does not model, so the design-mode
 * contact controls do nothing on them.
 *
 * The clamped disc's shape is `J_m(λu) − (J_m(λ)/I_m(λ))·I_m(λu)`, and the
 * modified Bessel function in the middle of it is the machinery this file
 * exists to no longer contain. The engine has it; design mode does without,
 * and the panel says which.
 */
export const SHAPELESS = new Set(['plate_round']);

