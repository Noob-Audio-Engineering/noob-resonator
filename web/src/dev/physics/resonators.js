/**
 * The largest stiff-string coefficient the Inharm control reaches, copied from
 * `dsp::engine::INHARM_B_MAX`. Ten times the value Lehtonen and colleagues
 * measured for a piano C4, so the physical region sits in the first third of
 * the travel and the rest is the synthetic extension.
 */
export const INHARM_B_MAX = 3.0e-3;

/**
 * The coefficient the control is asking for, from `Settings::inharm_b`.
 *
 * Quadratic in the control so that the region a real string lives in — `B`
 * around `3 × 10⁻⁴` for a piano C4 — sits where a knob can be placed on it
 * rather than in the first pixel.
 *
 * @param {number} inharm The control, −1 to 1.
 */
export const inharmB = (inharm) => {
  const x = Math.max(-1, Math.min(1, inharm));
  return INHARM_B_MAX * x * x * Math.sign(x);
};

/**
 * Inharm, applied to a series — **the engine's law, copied from
 * `Object::ratio`**, not a stand-in for it.
 *
 * `r → r·√(1 + |B|r²)` for a positive coefficient and `r → r/√(1 + |B|r²)` for
 * a negative one. The first is the stiff-string law, `fₙ = n·f₁·√(1 + Bn²)`,
 * which is one object's physics applied to every object here; the second is
 * the same expression run backwards, compressing the partials the way nothing
 * physical does, and the docs call that the synthetic half of the control.
 *
 * This file used to apply a log-axis stretch instead and say plainly that it
 * was not the stiff-string law. It was honest and it was still wrong, because
 * the engine's law *is* the stiff-string law and a stand-in that disagrees
 * with the thing it stands in for teaches the wrong shape.
 */
export const stretch = (ratios, inharm) => {
  const b = inharmB(inharm);
  if (b === 0) return ratios;
  const mag = Math.abs(b);
  return ratios.map((r) => {
    if (r === 0) return r;
    const s = Math.sqrt(1 + mag * r * r);
    return b > 0 ? r * s : r / s;
  });
};
